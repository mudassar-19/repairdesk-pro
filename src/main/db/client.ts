import path from 'node:path'
import fs from 'node:fs'
import { app, safeStorage } from 'electron'
import Database from 'better-sqlite3'
import { drizzle } from 'drizzle-orm/better-sqlite3'
import { migrate } from 'drizzle-orm/better-sqlite3/migrator'
import * as schema from './schema'

export type AppDatabase = ReturnType<typeof drizzle<typeof schema>>

/**
 * The type db.transaction()'s callback receives — structurally similar to
 * AppDatabase (same query builder methods) but not identical, so repository
 * constructors that need to run inside a transaction (see paymentService.ts)
 * accept this union rather than AppDatabase alone.
 */
export type DbTransaction = Parameters<AppDatabase['transaction']>[0] extends (tx: infer T) => unknown ? T : never
export type Db = AppDatabase | DbTransaction

let db: AppDatabase | null = null

/**
 * One fixed SQLite file per device, under Electron's userData dir — this app
 * is a standalone, offline-first local application with no cross-device or
 * cross-account concept: whichever account is logged in on this device reads
 * and writes this one file.
 */
export function getDatabasePath(): string {
  return path.join(app.getPath('userData'), 'repairdesk.sqlite')
}

/**
 * A brief window existed where each account got its own file under
 * userData/databases/{uid}.sqlite, to support multiple accounts safely
 * sharing one device (since replaced by scheduled cloud backups, which don't
 * need that). If this device passed through that window, its real data now
 * lives at one of those per-uid paths instead of the fixed one — this runs
 * once, before the fixed file is ever opened, to bring it back.
 *
 * Picks the file matching the currently logged-in local session's uid if
 * one exists (the account actually in use); otherwise, if there's exactly
 * one per-uid file left, adopts that unambiguously. If neither applies (no
 * session, or more than one file with no way to tell which is "current"),
 * it deliberately does nothing rather than guess — those files are left
 * exactly where they are, not deleted, so no data is ever lost even in the
 * unresolved case.
 */
function adoptPerAccountFileIfPresent(fixedPath: string): void {
  if (fs.existsSync(fixedPath)) return

  const databasesDir = path.join(app.getPath('userData'), 'databases')
  if (!fs.existsSync(databasesDir)) return

  const files = fs.readdirSync(databasesDir).filter((f) => f.endsWith('.sqlite'))
  if (files.length === 0) return

  const sessionUid = readSessionUid()
  const preferred = sessionUid ? `${sessionUid}.sqlite` : null
  const chosen = preferred && files.includes(preferred) ? preferred : files.length === 1 ? files[0] : null
  if (!chosen) return

  const fromBase = path.join(databasesDir, chosen).replace(/\.sqlite$/, '.sqlite')
  for (const suffix of ['', '-wal', '-shm']) {
    const from = fromBase + suffix
    if (fs.existsSync(from)) fs.renameSync(from, fixedPath + suffix)
  }
}

function readSessionUid(): string | null {
  try {
    const sessionPath = path.join(app.getPath('userData'), 'session.enc')
    if (!safeStorage.isEncryptionAvailable() || !fs.existsSync(sessionPath)) return null
    const encrypted = fs.readFileSync(sessionPath)
    const session = JSON.parse(safeStorage.decryptString(encrypted)) as { uid?: string }
    return session.uid ?? null
  } catch {
    return null
  }
}

/**
 * Opens (or creates) the local SQLite file and brings it up to date via
 * versioned Drizzle migrations (src/main/db/migrations, generated by
 * `npm run db:generate`). The main process bundles to a single
 * out/main/index.js, so __dirname at runtime is that file's directory
 * regardless of which source file this code came from — electron.vite.config.ts
 * has a build step that copies the migrations folder next to it at
 * out/main/db/migrations for both dev and packaged builds.
 *
 * scripts/seedQaData.ts loads this same module via tsx directly from
 * src/main/db/client.ts instead, where __dirname is src/main/db and the
 * migrations folder is right there (no db/ nesting) — fall back to that
 * layout when the compiled one isn't present, rather than assuming a build.
 */
function resolveMigrationsFolder(): string {
  const compiled = path.join(__dirname, 'db/migrations')
  return fs.existsSync(compiled) ? compiled : path.join(__dirname, 'migrations')
}

export function initDatabase(): AppDatabase {
  const dbPath = getDatabasePath()
  adoptPerAccountFileIfPresent(dbPath)

  const sqlite = new Database(dbPath)
  sqlite.pragma('journal_mode = WAL')
  // better-sqlite3's bundled SQLite defaults foreign_keys ON per connection —
  // every repository/service in this app was written assuming referential
  // integrity is NOT enforced at the DB layer, matching schema.ts's own
  // .references() calls being declarative only.
  sqlite.pragma('foreign_keys = OFF')

  db = drizzle(sqlite, { schema })
  migrate(db, { migrationsFolder: resolveMigrationsFolder() })

  return db
}

export function getDatabase(): AppDatabase {
  if (!db) {
    throw new Error('Database not initialized — call initDatabase() first')
  }
  return db
}

/**
 * Releases the live connection's file handle/lock so the on-disk file can be
 * safely replaced (backup restore). Only ever called immediately before an
 * app.relaunch()+app.exit() — nothing in this process reopens the connection
 * afterward, a fresh process does via the normal initDatabase() call.
 */
export function closeDatabase(): void {
  if (db) {
    db.$client.close()
    db = null
  }
}
